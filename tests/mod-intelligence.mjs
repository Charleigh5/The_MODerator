import assert from "node:assert/strict";
import {modIntelligenceCatalog} from "../.gauntlet-build/data/modIntelligence.js";
import {searchModCatalog,matchModSearch} from "../.gauntlet-build/lib/modLibrarySearch.js";
assert.equal(modIntelligenceCatalog.length, 37);
assert.equal(new Set(modIntelligenceCatalog.map(x=>x.id)).size,modIntelligenceCatalog.length,"unique canonical IDs required");
assert.equal(modIntelligenceCatalog.filter(x=>x.kind==="Community mod").length,31);
assert.equal(modIntelligenceCatalog.filter(x=>x.kind==="Code & tools").length,6);
assert(modIntelligenceCatalog.every(x=>x.url.startsWith("https://")), "trusted external source URLs required");
assert(modIntelligenceCatalog.every(x=>x.compatibility!=="GAME_VERIFIED"),"research is not runtime proof");
const roster=modIntelligenceCatalog.find(x=>x.title.includes("Ultimate Roster"));
assert.equal(roster.license,"REHOST_PROHIBITED");
assert.equal(roster.access,"MANUAL_ACCOUNT");
assert.equal(roster.compatibility,"EXACT_BUILD_NOT_VERIFIED");
assert(searchModCatalog("dark visors custom helmets").some(x=>x.title==="Madden 27 Unlocked"));
assert(searchModCatalog("salary progression franchise").some(x=>x.title==="SABOS Franchise Mod 1.2"));
assert(searchModCatalog("C# frostbite compiler","Code & tools").some(x=>x.title==="FMT Madden 27 Profile & Compiler"));
assert(searchModCatalog("stadium ribbonboard advertisements").some(x=>x.title==="Stadium Experience"));
assert(searchModCatalog("tune coach mode CPU vs CPU").some(x=>x.title==="Coach Mode / SlowSim"));
assert.equal(searchModCatalog("unlikely_nonmatching_test_abc_xyz").length,0);
assert.equal(searchModCatalog("All", "Code & tools", "Equipment").length,0);
assert(modIntelligenceCatalog.some(x=>x.evidence==="INSUFFICIENT_IMPLEMENTATION"&&x.reuse==="DO_NOT_RECOMMEND"));
assert(modIntelligenceCatalog.some(x=>x.license==="CC-BY-NC-ND-4.0"&&x.reuse==="NO_DERIVATIVE_REUSE"));
assert(matchModSearch(roster,"draft rookies")>=0);
