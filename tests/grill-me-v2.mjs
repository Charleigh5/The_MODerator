import assert from "node:assert/strict";
import {startGrillSession,currentGrillQuestion,chooseGrillOption,previousGrillRound,confirmGrillBrief,createGridironModSpecV2} from "../.gauntlet-build/lib/grillMeFlow.js";
const request="A 95 rated safety should read routes and pursue better than a 72 rated safety without superhuman outcomes";
let s=startGrillSession(request);
assert.equal(s.archetype,"SAFETY_RECOGNITION");
assert.equal(currentGrillQuestion(s).round,"MECHANISM");
assert.deepEqual(currentGrillQuestion(s).options.map(x=>x.id),["A","B","C","D"]);
assert.throws(()=>createGridironModSpecV2(s,{readiness:"BLOCKED",effects:[]}),/Confirm/);
const a=chooseGrillOption(s,"A"),c=chooseGrillOption(s,"C");
assert.notEqual(currentGrillQuestion(a).question,currentGrillQuestion(c).question);
assert.throws(()=>chooseGrillOption(s,"D"),/custom detail/);
assert.throws(()=>chooseGrillOption(s,"E"),/option/);
assert.equal(chooseGrillOption(s,"D","Focus on pattern-match pass coverage").answers.MECHANISM.id,"D");
s=chooseGrillOption(a,"A");
assert.equal(currentGrillQuestion(s).round,"SEPARATION");
s=chooseGrillOption(s,"A");
assert.equal(currentGrillQuestion(s).round,"CONFIRM");
assert.equal(previousGrillRound(s).answers.SEPARATION,undefined);
assert.throws(()=>createGridironModSpecV2(s,{readiness:"BLOCKED",effects:[]}),/Confirm/);
s=confirmGrillBrief(s);
const intent={readiness:"BLOCKED",effects:[{matches:[{capability:{id:"CANDIDATE-AI",surface:"GAMEPLAY_AI",evidence:"CANDIDATE"},parity:"UNKNOWN"}]}]};
const spec=createGridironModSpecV2(s,intent);
assert.equal(spec.version,"GRIDIRON_MOD_SPEC_V2");
assert.equal(spec.titleBuild,null);
assert.equal(spec.gameArtifactStatus,"GAME_ARTIFACT_NOT_BUILT");
assert.equal(spec.runtimeStatus,"NOT_RUN");
assert.equal(spec.confirmedByUser,true);
assert.equal(spec.bindingEvidence[0].status,"CANDIDATE");
assert.equal(spec.testPlan.metricTargets.status,"PROPOSED_NOT_MEASURED");
assert.deepEqual(spec.requestedPositions,["FS","SS"]);
assert.equal(spec.id,createGridironModSpecV2(s,intent).id);
assert.equal(startGrillSession("Change stadium graphics").archetype,"GENERAL_MOD");
assert.throws(()=>startGrillSession("x".repeat(4001)),/4,000/);
console.log("GRILL_ME_V2_PASS branching=1 revision=1 confirmation=1 reality_gate=1");
